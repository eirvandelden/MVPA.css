require "minitest/autorun"
require_relative "css_source_helper"
require_relative "color_contrast_helper"

# solunized-light and the default light palette carry the Solarized cream backgrounds,
# so they no longer look like the neutral solunized-white.
class SolunizedLightCreamTest < Minitest::Test
  include CssSourceHelper
  include ColorContrastHelper

  COLORS = "4_theme/0_colors.css".freeze
  CREAM = {
    "bg-0" => "oklch(97.35% 0.0261 90.10)",
    "bg-1" => "oklch(93.06% 0.0260 92.40)",
    "bg-2" => "oklch(86.37% 0.0293 91.67)"
  }.freeze
  WHITE = {
    "bg-0" => "oklch(100.00% 0.0000 89.88)",
    "bg-1" => "oklch(95.64% 0.0079 216.62)"
  }.freeze

  def test_solunized_light_has_the_solarized_cream_backgrounds
    each_source(COLORS) do |name, css|
      body = rule_body(css, '[data-theme="solunized-light"]')

      CREAM.each { |token, value| assert_includes body, "--color-#{token}: #{value};", "#{name} #{token}" }
    end
  end

  def test_solunized_light_page_background_has_a_yellow_hue
    each_source(COLORS) do |name, css|
      _lightness, chroma, hue = oklch(rule_body(css, '[data-theme="solunized-light"]'), "bg-1")

      assert_operator chroma, :>, 0.015, name
      assert_includes 60..110, hue, name
    end
  end

  def test_solunized_white_keeps_its_neutral_backgrounds
    each_source(COLORS) do |name, css|
      body = rule_body(css, '[data-theme="solunized-white"]')

      WHITE.each { |token, value| assert_includes body, "--color-#{token}: #{value};", "#{name} #{token}" }
    end
  end

  def test_default_light_palette_matches_solunized_light
    each_source(COLORS) do |name, css|
      default = rule_bodies(css, ":root").find { |body| body.include?("--color-bg-0:") }

      CREAM.each_key do |token|
        assert_equal declared(rule_body(css, '[data-theme="solunized-light"]'), token), declared(default, token),
                     "#{name} #{token}"
      end
    end
  end

  def test_cards_are_lighter_and_borders_darker_than_the_page
    each_source(COLORS) do |name, css|
      [ rule_body(css, '[data-theme="solunized-light"]'),
        rule_bodies(css, ":root").find { |body| body.include?("--color-bg-0:") } ].each do |body|
        lightness = %w[bg-0 bg-1 bg-2].map { |token| oklch(body, token).first }

        assert_equal lightness.sort.reverse, lightness, name
        assert_equal 3, lightness.uniq.size, name
      end
    end
  end

  def test_light_mapping_puts_cards_on_bg_0_and_borders_on_bg_2
    each_source(COLORS) do |name, css|
      mapping = rule_bodies(css, '[data-theme="solunized-light"]').find { |body| body.include?("--color-bg:") }
      default = rule_bodies(css, ":root").find { |body| body.include?("--color-bg-lighter:") }

      [ mapping, default ].each do |body|
        assert_includes body, "--color-bg: var(--color-bg-1);", name
        assert_includes body, "--color-bg-lighter: var(--color-bg-0);", name
        assert_includes body, "--color-bg-darkest: var(--color-bg-2);", name
      end
      assert_includes rule_bodies(css, ":root").join, "--color-border: var(--color-bg-darkest);", name
    end
  end

  def test_body_text_on_the_cream_page_meets_wcag_aa
    each_source(COLORS) do |name, css|
      body = rule_body(css, '[data-theme="solunized-light"]')
      ratio = contrast(luminance(*oklch(body, "fg-0")), luminance(*oklch(body, "bg-1")))

      assert_operator ratio, :>=, 4.5, name
    end
  end

  def test_the_stylesheets_carry_no_generator_marker
    each_source(COLORS) do |name, css|
      refute_match(/generated by/i, css, name)
      refute_match(/do not edit directly/i, css, name)
    end
  end
end
